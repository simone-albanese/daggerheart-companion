function seed(patch: Partial<Character> = {}): Character {
  const character = { ...playedCharacter(), ...patch };
  useApp.setState({
    ready: true,
    storageError: null,
    dataset,
    index,
    characters: [character],
    activeId: character.id,
    prefs: { ...DEFAULT_PREFS },
    log: [],
    openCard: null,
  });
  return character;
}

const play = (c: Character): void => {
  render(createElement(Play, { stats: playedStats(c) }));
};

/**
 * A class in this dataset that grants no dice pool, ASKED rather than named.
 *
 * The fixture's class is `dataset.classes[0]`, which today is the Bard - and a
 * Bard has a Rally Die, so `Play` draws it the `Dice pools` fold. That fold is
 * real and it costs 52px, but it is NOT what the budget below is a budget for:
 * `STACK` and `INDEX` sum the sheet every character has, and three archetypes
 * out of the book carry one more section than that. `carries one more fold for
 * a character with a dice pool, and says what it costs` asserts the other half.
 *
 * Derived by asking `poolsFor` rather than by writing `wizard` here, for the
 * reason `fixture.ts` gives about pinned ids: the SRD is regenerated by
 * `tools/build-srd.ts`, and a literal would rot the day the classes reorder.
 * Only the class is patched - the subclass, the cards, the gear and the
 * Experiences stay exactly as the fixture built them, so the column's SHAPE is
 * the fixture's and only the feature list underneath it differs.
 */
const POOLLESS: string = (() => {
  const base = playedCharacter();
  const found = dataset.classes.find((k) => {
    const c = { ...base, classRef: k.id };
    // No pool AND no Beastform: the two class-conditional sections this column
    // has. Swapping the Bard's `Dice pools` for a Druid's Beastform banner
    // would have kept the child count at seven and proved nothing - which is
    // exactly what the first version of this did.
    return poolsFor(c, index, playedStats(c)).length === 0 && !hasBeastform(c, index);
  });
  if (found === undefined) {
    throw new Error('every class in this dataset draws a conditional section');
  }
  return found.id;
})();

/** The fixture, minus the one section that is not on every sheet. */
const noPool = (): Character => seed({ classRef: POOLLESS });

/**
 * The same sheet, edited under the screen - what Build does to a character the
 * player then comes back to.
 *
 * It keeps the id and it keeps the mounted tree, because that is the whole
 * point: `Play` holds the armed declaration in its own state, so a fixture that
 * unmounted and remounted would answer a question nobody is asking.
 */
function rebuild(patch: Partial<Character>): Character {
  const next = { ...useApp.getState().characters[0]!, ...patch };
  act(() => {
    useApp.setState({ characters: [next] });
  });
  play(next);
  return next;
}

/**
 * The header's character picker, as the store sees it: another sheet arrives
 * beside this one and becomes the active one, with `Play` never unmounting.
 */
function switchTo(c: Character): void {
  act(() => {
    useApp.setState((s) => ({ characters: [...s.characters, c], activeId: c.id }));
  });
  play(c);
}

const text = (): string => container.textContent ?? '';

const buttons = (): HTMLButtonElement[] => [...container.querySelectorAll('button')];

/** The disclosure header for a section, by the label it prints. */
function fold(label: string): HTMLButtonElement {
  const found = buttons().find(
    (b) => b.getAttribute('aria-expanded') !== null && (b.textContent ?? '').startsWith(label),
  );
  if (found === undefined) {
    throw new Error(
      `no disclosure called "${label}". Folds here: ${buttons()
        .filter((b) => b.getAttribute('aria-expanded') !== null)
        .map((b) => b.textContent)
        .join(' | ')}`,
    );
  }
  return found;
}

