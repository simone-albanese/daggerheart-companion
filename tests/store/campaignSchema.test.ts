const FIXTURES = fileURLToPath(new URL('../fixtures/schema', import.meta.url));

const readFixture = (version: number): Record<string, unknown> =>
  JSON.parse(readFileSync(join(FIXTURES, `v${version}.campaign.json`), 'utf8')) as Record<
    string,
    unknown
  >;

const versions = (): number[] =>
  readableVersions(OLDEST_READABLE_CAMPAIGN, CAMPAIGN_SCHEMA_VERSION);

/** A minimal record: only what `readCampaignRecord` genuinely insists on. */
const bare = (patch: Record<string, unknown> = {}): Record<string, unknown> => ({
  id: 'campaign-1',
  schemaVersion: CAMPAIGN_SCHEMA_VERSION,
  name: 'A Campaign',
  ...patch,
});

describe('the policy, applied to a second schema', () => {
  it('numbers campaigns separately from characters, on purpose', () => {
    // Not an accident of ordering: folding campaigns into SCHEMA_VERSION would
    // make every future campaign change a character migration, and force every
    // committed character fixture to be rewritten for a field no character has.
    expect(CAMPAIGN_SCHEMA_VERSION).not.toBe(SCHEMA_VERSION);
  });

  it('has a converter for every step from the oldest readable version to this one', () => {
    const gaps = missingConverters(
      OLDEST_READABLE_CAMPAIGN,
      CAMPAIGN_SCHEMA_VERSION,
      CAMPAIGN_MIGRATIONS,
    );
    expect(
      gaps,
      `campaign schema ${gaps.join(', ')} can be read by no converter in shared/campaigns.ts.`,
    ).toEqual([]);
  });

  it('would fail on a bump that shipped without its converter', () => {
    // The teeth, without touching the constant. If this ever comes back empty
    // the check above has gone vacuous - passing because the range is empty
    // rather than because it is covered.
    expect(
      missingConverters(
        CAMPAIGN_SCHEMA_VERSION,
        CAMPAIGN_SCHEMA_VERSION + 1,
        CAMPAIGN_MIGRATIONS,
      ),
    ).toEqual([CAMPAIGN_SCHEMA_VERSION]);
  });

  it('carries no converter for a version this build has not left yet', () => {
    const ahead = CAMPAIGN_MIGRATIONS.filter((m) => m.from >= CAMPAIGN_SCHEMA_VERSION);
    expect(ahead.map((m) => m.from)).toEqual([]);
  });

  it('gives every converter a line of changelog', () => {
    for (const m of CAMPAIGN_MIGRATIONS) {
      expect(m.note.trim().length, `campaign schema ${m.from}`).toBeGreaterThan(0);
    }
  });
});

describe('the committed fixtures', () => {
  it('has one per readable version', () => {
    for (const version of versions()) {
      expect(() => readFixture(version), `no committed fixture for campaign v${version}`).not.toThrow();
    }
  });

  it('keeps each fixture at the version its name claims', () => {
    // A fixture rewritten by a later build proves only that the current code
    // can read its own output, which is not the question being asked.
    for (const version of versions()) {
      expect(readFixture(version)['schemaVersion'], `v${version}.campaign.json`).toBe(version);
    }
  });

  for (const version of versions()) {
    it(`still opens the campaign schema ${version} record whole`, () => {
      const { campaign, warnings } = readCampaignRecord(readFixture(version));

      /*
       * One warning, and it is the party row.
       *
       * Every committed fixture carries the same nine-field stand-in where a
       * character should be - `armorSlots`, `hope`, `hp`, `id`, `level`, `name`,
       * `pronouns`, `schemaVersion`, `stress` - which was enough to store and
       * never enough to draw. `readPartyMember` refuses it now, so this walk
       * expects the refusal rather than silence. The fixtures are NOT
       * regenerated to make it go away: a fixture rewritten by a later build
       * proves only that the current code can read its own output, which is the
       * rule this whole file exists to keep.
       */
      expect(warnings).toHaveLength(1);
      expect(warnings[0]).toMatch(/not a whole character/);
      expect(campaign.schemaVersion).toBe(CAMPAIGN_SCHEMA_VERSION);

      // Not just "it parsed". These are the things a GM would notice missing.
      expect(campaign.name).toBe('The Sablewood Winter');
      expect(campaign.fear).toBe(7);
      /*
       * The five rows every fixture has carried since v1, in the order they
       * were written, at the front of the list.
       *
       * `slice` rather than the whole array because a later fixture is the
       * same table with the rows that schema added on the end - v2 has a `url`
       * and a `note` after these - and pinning the whole list would mean the
       * bump rewriting this assertion, which is the one thing a frozen fixture
       * exists to stop. It is still exact about these five: a fixture that lost
       * one, reordered two, or read a `link` as `unreadable` fails here, because
       * `slice(0, 5)` of a shorter list is shorter and `toEqual` is not a
       * prefix match.
       */
      expect(campaign.session.slice(0, 5).map((i) => i.kind)).toEqual([
        'scene',
        'encounter',
        'countdown',
        'link',
        'link',
      ]);
      expect(campaign.board.environmentRef).toBe('raging-river');
      // The row is gone, and the sentence that took it away names the
      // character, which is the only part of a refusal a GM can act on.
      expect(campaign.party).toEqual([]);
      expect(warnings[0]).toContain('Ilya of the Ninth');

      const fight = campaign.session.find((i) => i.kind === 'encounter');
      expect(fight?.kind === 'encounter' && fight.roster).toHaveLength(2);
      expect(fight?.kind === 'encounter' && fight.combatants[0]?.hp.marked).toBe(3);

      expect(primaryCountdownOf(campaign.session)?.value).toBe(4);
    });
  }
});

describe('a campaign owns its own things, and not the player characters', () => {
  it('holds a name, a session list, Fear, countdowns and a party', () => {
    const c = newCampaign('Ashes of Rivermarch', '2026-08-16T10:00:00.000Z', 'campaign-1');
    expect(c.name).toBe('Ashes of Rivermarch');
    expect(c.session).toEqual([]);
    expect(c.fear).toBe(0);
    expect(c.party).toEqual([]);
    expect(c.board).toEqual(emptyBoard());
  });

  it('stamps itself with the campaign schema, never the character one', () => {
    const c = newCampaign('x', '2026-08-16T10:00:00.000Z', 'campaign-1');
    expect(c.schemaVersion).toBe(CAMPAIGN_SCHEMA_VERSION);
  });
});

describe('the two refusals, and nothing else', () => {
  it('will not read a record a newer build wrote, and says to update the app', () => {
    expect(() =>
      readCampaignRecord(bare({ schemaVersion: CAMPAIGN_SCHEMA_VERSION + 1 })),
    ).toThrow(SchemaError);
    expect(() =>
      readCampaignRecord(bare({ schemaVersion: CAMPAIGN_SCHEMA_VERSION + 1 })),
    ).toThrow(/newer version of the app.*Update the app/s);
  });

  it('will not read a record with no id, because there is nothing to write back to', () => {
    // Inventing one here is how a campaign gets duplicated on every launch.
    const { id, ...rest } = bare();
    expect(id).toBeDefined();
    expect(() => readCampaignRecord(rest)).toThrow(CampaignReadError);
    expect(() => readCampaignRecord(rest)).toThrow(/nothing to write it back to/);
  });

  it('opens a record that is otherwise almost empty', () => {
    const { campaign } = readCampaignRecord(bare());
    expect(campaign.name).toBe('A Campaign');
    expect(campaign.session).toEqual([]);
    expect(campaign.board.region).toBe('encounter');
    expect(campaign.board.partyTier).toBe(1);
  });

  it('reads a record with no stamp as this build’s, the way a hand-edited file arrives', () => {
    const { schemaVersion, ...rest } = bare();
    expect(schemaVersion).toBe(CAMPAIGN_SCHEMA_VERSION);
    expect(readCampaignRecord(rest).campaign.schemaVersion).toBe(CAMPAIGN_SCHEMA_VERSION);
  });

  /*
   * `board.region` is a union in the type and a list in the reader, and only
   * the list is load-bearing on the way in from a disk. Widening one and
   * forgetting the other used to typecheck perfectly and lose the new tool on
   * every single reload - silently, because the fallback is a real region.
   *
   * That hole is closed in the source rather than here: `GM_REGIONS` is the
   * keys of a `Record<GmRegion, true>`, so a region with no entry is a missing
   * property and an entry that is not a region is an excess one. This case can
   * only ever loop the list it is given, which is exactly why it could not hold
   * the hazard its own comment described - it named `'reference'` as "the one
   * added last" and stayed green through two more regions being added after it.
   */
  it('keeps every region this build knows, one at a time', () => {
    for (const region of GM_REGIONS) {
      const { campaign } = readCampaignRecord(bare({ board: { region } }));
      expect(campaign.board.region, `${region} did not survive a read`).toBe(region);
    }
    // Not vacuous: an empty list would pass the loop above in silence.
    expect(GM_REGIONS.length).toBeGreaterThan(1);
  });

  it('falls back for a region no build knows, which is what makes widening safe', () => {
    // The guarantee the reference tab was added on: an older build meeting a
    // newer record forgets which tool was open and loses nothing else.
    const { campaign } = readCampaignRecord(bare({ board: { region: 'holodeck' } }));
    expect(campaign.board.region).toBe('encounter');
  });
});

describe('a session item this build cannot read', () => {
  const withItem = (item: unknown): Campaign =>
    readCampaignRecord(bare({ session: [item] })).campaign;

  it('is kept and named, not dropped', () => {
    // The failure this repo has shipped twice: the list comes back one row
    // shorter and the GM has no way to learn which row it was.
    const kept = withItem({ id: 'i1', kind: 'handout', name: 'The letter' });
    expect(kept.session).toHaveLength(1);
    expect(kept.session[0]!.kind).toBe('unreadable');
    expect(kept.session[0]!.name).toBe('The letter');
  });

  it('says what it was, in a sentence a screen can print', () => {
    const item = withItem({ id: 'i1', kind: 'handout', name: 'The letter' }).session[0]!;
    expect(item.kind === 'unreadable' && item.why).toMatch(/no "handout" item/);
  });

  it('keeps the bytes it arrived as, so nothing is actually lost', () => {
    const item = withItem({ id: 'i1', kind: 'handout', url: 'x', name: '' }).session[0]!;
    expect(item.kind === 'unreadable' && JSON.parse(item.raw)).toMatchObject({
      kind: 'handout',
      url: 'x',
    });
  });

  it('does not wrap an already-wrapped item a second time', () => {
    const once = withItem({ id: 'i1', kind: 'handout', name: 'x' }).session[0]!;
    const twice = withItem(once).session[0]!;
    expect(twice.kind === 'unreadable' && JSON.parse(twice.raw)).toMatchObject({ kind: 'handout' });
  });

  it('warns about it, rather than only recording it', () => {
    const { warnings } = readCampaignRecord(bare({ session: [{ id: 'i1', kind: 'handout' }] }));
    expect(warnings.join(' ')).toMatch(/could not be read/);
  });
});

/*
 * A `link` row, which is still the in-app one.
 *
 * Campaign schema 2 added a `url` row beside it - a different kind, with its own
 * reader and its own six mitigations, exercised in
 * `tests/store/campaignUrlRow.test.ts`. `LINK_KINDS` did not gain a fifth
 * entry, and this describe is about the four that were always there.
 */
describe('a link row, which still never leaves the app', () => {
  const target = (t: unknown): SessionItem =>
    readCampaignRecord(bare({ session: [{ id: 'i1', kind: 'link', name: 'n', target: t }] }))
      .campaign.session[0]!;

  it('reads the four things a link may point at', () => {
    for (const kind of ['adversary', 'environment', 'domainCard', 'rule']) {
      const item = target({ kind, ref: 'r' });
      expect(item.kind === 'link' && item.target.kind).toBe(kind);
    }
  });

  it('keeps a target it does not recognise, and remembers what it called itself', () => {
    const item = target({ kind: 'campaignFrame', ref: 'the-witherwild' });
    expect(item.kind).toBe('link');
    expect(item.kind === 'link' && item.target.kind).toBe('unknown');
    expect(item.kind === 'link' && item.target.kind === 'unknown' && item.target.named).toBe(
      'campaignFrame',
    );
    expect(item.kind === 'link' && item.target.ref).toBe('the-witherwild');
  });

  it('keeps the ref even when there is no kind at all', () => {
    const item = target({ ref: 'the-witherwild' });
    expect(item.kind === 'link' && item.target.ref).toBe('the-witherwild');
  });
});

describe('countdowns, which live in the session list', () => {
  const countdownItem = (id: string, primary: boolean): Record<string, unknown> => ({
    id,
    kind: 'countdown',
    name: id,
    primary,
    countdown: { id, name: id, kind: 'standard', start: 4, value: 2, notes: '' },
  });

  it('collects them in list order', () => {
    const { campaign } = readCampaignRecord(
      bare({ session: [countdownItem('a', false), countdownItem('b', true)] }),
    );
    expect(countdownsOf(campaign.session).map((c) => c.id)).toEqual(['a', 'b']);
  });

  it('lets at most one be the primary one', () => {
    // Two rows both claiming to be the one the GM is watching is not a state
    // any screen can draw honestly, and a hand-edited file can reach it.
    const { campaign, warnings } = readCampaignRecord(
      bare({ session: [countdownItem('a', true), countdownItem('b', true)] }),
    );
    expect(campaign.session.filter((i) => i.kind === 'countdown' && i.primary)).toHaveLength(1);
    expect(primaryCountdownOf(campaign.session)?.id).toBe('a');
    expect(warnings.join(' ')).toMatch(/more than one countdown/);
  });

  it('moves the flag rather than adding a second one', () => {
    const { campaign } = readCampaignRecord(
      bare({ session: [countdownItem('a', true), countdownItem('b', false)] }),
    );
    const moved = withPrimaryCountdown(campaign.session, 'b');
    expect(moved.filter((i) => i.kind === 'countdown' && i.primary).map((i) => i.id)).toEqual(['b']);
  });

  it('clears the flag when told to make a non-countdown primary', () => {
    const { campaign } = readCampaignRecord(bare({ session: [countdownItem('a', true)] }));
    expect(withPrimaryCountdown(campaign.session, null).some((i) => i.kind === 'countdown' && i.primary)).toBe(
      false,
    );
  });

  it('brings a countdown value back inside its own start', () => {
    const { campaign } = readCampaignRecord(
      bare({
        session: [
          {
            id: 'a',
            kind: 'countdown',
            name: 'a',
            primary: false,
            countdown: { id: 'a', name: 'a', kind: 'standard', start: 4, value: 99, notes: '' },
          },
        ],
      }),
    );
    expect(countdownsOf(campaign.session)[0]!.value).toBe(4);
  });
});

describe('the repairs, which never cost the record', () => {
  it('brings a Fear pool from outside the ladder back onto it, and says so', () => {
    const { campaign, warnings } = readCampaignRecord(bare({ fear: 99 }));
    expect(campaign.fear).toBe(MAX_FEAR);
    expect(warnings.join(' ')).toMatch(/Fear pool held 99/);
  });

  it('re-numbers the order so a list written without one keeps its order', () => {
    const { campaign } = readCampaignRecord(
      bare({
        session: [
          { id: 'a', kind: 'scene', name: 'a' },
          { id: 'b', kind: 'scene', name: 'b' },
          { id: 'c', kind: 'scene', name: 'c' },
        ],
      }),
    );
    expect(campaign.session.map((i) => i.id)).toEqual(['a', 'b', 'c']);
    expect(campaign.session.map((i) => i.order)).toEqual([0, 1, 2]);
  });

  it('sorts by the order it was given, when it was given one', () => {
    const { campaign } = readCampaignRecord(
      bare({
        session: [
          { id: 'a', kind: 'scene', name: 'a', order: 2 },
          { id: 'b', kind: 'scene', name: 'b', order: 0 },
        ],
      }),
    );
    expect(campaign.session.map((i) => i.id)).toEqual(['b', 'a']);
  });

  it('leaves out a party row with no sheet, and one with half a sheet, and says both', () => {
    /*
     * The rule `gmStore.load()` already had - a row with no sheet has no
     * numbers and takes the screen down - and the clause added beside it. `p2`
     * used to survive this assertion: a name and nothing else was enough to be
     * stored and was never enough for `deriveStats`, and it is the shape that
     * took the GM screen down with `levelUpHistory.filter`. Two refusals, two
     * different sentences, and `p3` shows the campaign is not what is refused.
     */
    const { campaign, warnings } = readCampaignRecord(
      bare({
        party: [
          { id: 'p1' },
          { id: 'p2', sheet: { name: 'Kesh' } },
          { id: 'p3', sheet: newCharacter({ name: 'Ilya of the Ninth' }) },
        ],
      }),
    );
    expect(campaign.party.map((m) => m.id)).toEqual(['p3']);
    expect(warnings.join(' ')).toMatch(/no character sheet/);
    expect(warnings.join(' ')).toMatch(/"Kesh" is not a whole character|"Kesh"/);
  });

  it('does not accept a party tier the game has no tier for', () => {
    expect(readCampaignRecord(bare({ board: { partyTier: 9 } })).campaign.board.partyTier).toBe(1);
  });
});

describe('walking a campaign record forward', () => {
  it('passes a current record through untouched, and stamps it', () => {
    const { record, from, applied } = migrateCampaignRecord({
      schemaVersion: CAMPAIGN_SCHEMA_VERSION,
      x: 1,
    });
    expect(record).toEqual({ schemaVersion: CAMPAIGN_SCHEMA_VERSION, x: 1 });
    expect(from).toBe(CAMPAIGN_SCHEMA_VERSION);
    expect(applied).toEqual([]);
  });

  it('refuses a version below the oldest any build has written', () => {
    expect(() => migrateCampaignRecord({ schemaVersion: OLDEST_READABLE_CAMPAIGN - 1 })).toThrow(
      /no released version of this app has ever written/,
    );
  });

  it('carries the version on the error, so a caller can say which record', () => {
    try {
      migrateCampaignRecord({ schemaVersion: CAMPAIGN_SCHEMA_VERSION + 4 });
      expect.unreachable('should have thrown');
    } catch (error) {
      expect(error).toBeInstanceOf(SchemaError);
      expect((error as SchemaError).version).toBe(CAMPAIGN_SCHEMA_VERSION + 4);
    }
  });
});

describe('what campaign schema 3 added, held down', () => {
  /*
   * The gate's own lesson, applied while the paint is wet: a green suite is not
   * a verification. Each of these fails if the field it names stops surviving a
   * read, which is the only property the bump actually bought.
   */
  const v3 = (): Record<string, unknown> => readFixture(3);

  it('carries the fight on the scene row, which is the whole of decision 1', () => {
    const { campaign } = readCampaignRecord(v3());
    const scene = campaign.session.find((i) => i.kind === 'scene');
    expect(scene?.kind === 'scene' && scene.roster).toEqual([
      { ref: 'jagged-knife-bandit', count: 2 },
    ]);
    expect(scene?.kind === 'scene' && scene.adjustments.harder).toBe(true);
    // The fight as it is being fought is never in the plan, only the plan for it.
    expect(scene?.kind === 'scene' && scene.combatants).toEqual([]);
  });

  it('still reads the legacy encounter row, because saved campaigns carry one', () => {
    /*
     * The half of decision 1 that is easy to lose. `encounter` left
     * `SESSION_ITEM_KINDS` so nothing can mint one; the union arm stayed so
     * every campaign already on a disk still opens. A build that dropped the
     * arm would read this row as `unreadable` and then write that back.
     */
    const { campaign, warnings } = readCampaignRecord(v3());
    const enc = campaign.session.find((i) => i.kind === 'encounter');
    expect(enc?.kind).toBe('encounter');
    expect(enc?.kind === 'encounter' && enc.roster.length).toBeGreaterThan(0);
    // Nothing in the session list needed saying. The fixture's party stub is
    // refused whatever this row does, and the walk above is where that is held.
    expect(warnings.filter((w) => !w.includes('not a whole character'))).toEqual([]);
  });

  it('keeps the triad, the owner and every beat on a countdown', () => {
    const { campaign } = readCampaignRecord(v3());
    const row = campaign.session.find((i) => i.kind === 'countdown');
    const clock = row?.kind === 'countdown' ? row.countdown : null;
    expect(clock?.activation).toBe('the party first sets foot on the ice');
    expect(clock?.advancement).toBe('one tick per failed crossing roll');
    expect(clock?.effect).toBe('the ice gives way and everyone standing on it falls in');
    expect(clock?.owner).toBe('9a1f2b3c-4d5e-4f60-8712-a3b4c5d6e7f8');
    expect(clock?.beats).toEqual([
      'a crack runs out from the bank',
      'water wells up over the boots',
    ]);
  });

  it('leaves the beats alone when there are fewer of them than there are ticks', () => {
    // A GM who has written the first two beats of a six-tick clock is the
    // normal case. Padding would make "unwritten" and "deliberately blank"
    // indistinguishable; truncating would eat words on a clock that shortened.
    const { campaign } = readCampaignRecord(v3());
    const row = campaign.session.find((i) => i.kind === 'countdown');
    const clock = row?.kind === 'countdown' ? row.countdown : null;
    expect(clock?.beats.length).toBe(2);
    expect(clock?.start).toBe(6);
  });

  it('opens the archive and the register, and orders the archive by when it closed', () => {
    const { campaign } = readCampaignRecord(v3());
    expect(campaign.archive).toHaveLength(1);
    expect(campaign.archive[0]!.name).toBe('The first night out');
    expect(campaign.archive[0]!.items.map((i) => i.kind)).toEqual(['scene']);
    expect(campaign.register.map((e) => e.name)).toContain('Old Hessa, the ferrywoman');
  });

  it('wraps a register entry whose kind this build has never heard of', () => {
    /*
     * The same promise `SessionItem` and `LinkTarget` make, made again one
     * level down. A GM who wrote forty people and finds thirty-nine has no way
     * to learn which one left, so an entry this build cannot read comes back
     * out of the file it went into.
     */
    const { campaign } = readCampaignRecord(v3());
    const odd = campaign.register.find((e) => e.kind === 'unreadable');
    expect(odd).toBeDefined();
    expect(odd?.name).toBe('The drowned king returns');
    expect(odd?.kind === 'unreadable' && odd.why).toContain('prophecy');
    expect(odd?.kind === 'unreadable' && odd.raw).toContain('prophecy');
  });

  it('a campaign written now and read back keeps both new arrays', () => {
    // `newCampaign` seeds them, the reader names them. A `Campaign` literal
    // that forgot either would drop it on the first save/load round trip.
    const { campaign } = readCampaignRecord(bare({ archive: [], register: [] }));
    expect(campaign.archive).toEqual([]);
    expect(campaign.register).toEqual([]);
  });
});

describe('the bumps, and the record they must not touch', () => {
  /*
   * The whole justification for schema 2, restated as an assertion.
   *
   * The version moved so that an *older* build refuses a record carrying a
   * `url` or a `note` row. Without the bump, `readSessionItem` in the old build
   * wraps both as `unreadable` - on purpose, so the row is kept and named - and
   * `gmStore`'s 400ms debounce then writes that reading back, so the GM's row
   * is destroyed on the older device and nothing anywhere says why.
   *
   * Nothing in a v1 record is wrong, so the converter changes no field.
   *
   * Schema 3 is the same argument with more at stake. It moved so that an older
   * build refuses a record whose `scene` rows carry a fight, whose countdowns
   * carry the Activation / Advancement / Effect triad, and which has an
   * `archive` and a `register` at all - every one of which a schema-2 reader
   * would drop on the floor and then write back over. Nothing in a v2 record is
   * wrong either, so that converter changes no field either.
   */
  it('carries one converter per bump, in order, and none of them is a repair', () => {
    // Derived from the constant rather than frozen as a literal: a third bump
    // adds one entry here and does not have to remember to edit two lines.
    expect(CAMPAIGN_MIGRATIONS.map((m) => m.from)).toEqual([1, 2]);
    expect(CAMPAIGN_SCHEMA_VERSION).toBe(3);
    expect(CAMPAIGN_MIGRATIONS).toHaveLength(CAMPAIGN_SCHEMA_VERSION - OLDEST_READABLE_CAMPAIGN);
  });

  it('gives a v1 record back byte for byte, apart from the stamp, across both bumps', () => {
    // Deep equality against the fixture itself rather than against a list of
    // fields somebody remembered to check: an `apply` that dropped `party`,
    // renamed `board.partyTier`, or normalised a countdown on the way through
    // fails here without anyone having to have predicted which field it was.
    const fixture = readFixture(1);
    const { record, from, applied } = migrateCampaignRecord(fixture);

    expect(from).toBe(1);
    // Both converters ran, in order, and each said what it was for.
    expect(applied).toEqual(CAMPAIGN_MIGRATIONS.map((m) => m.note));
    expect(record).toEqual({ ...fixture, schemaVersion: CAMPAIGN_SCHEMA_VERSION });
    // Deep equality is not enough on its own to earn the words "byte for byte":
    // `toEqual` ignores key order and treats an absent key and an
    // `undefined`-valued one as the same. The `.dhcampaign` checksum is
    // computed over `JSON.stringify`, so a converter that reordered keys or
    // turned a value into `undefined` would pass the line above and still make
    // the file this app writes fail to verify against the file it reads.
    expect(JSON.stringify(record)).toBe(
      JSON.stringify({ ...fixture, schemaVersion: CAMPAIGN_SCHEMA_VERSION }),
    );
    // Said separately, because the two assertions above would also pass if both
    // sides were 1 and the bump had never happened.
    expect(record['schemaVersion']).toBe(3);
  });

  it('hands the chain a copy rather than the record it was given', () => {
    /*
     * Asserted against `applyChain` and not against `migrateCampaignRecord`,
     * because the wrapper spreads a `schemaVersion` onto whatever comes back
     * and that spread allocates an object either way - so a test one level up
     * passes whether the converter copies or returns its argument, which is a
     * test that cannot fail.
     *
     * This one can: `apply: (r) => r` turns the first assertion red. It matters
     * because the chain is the one part of the schema policy that is pure, and
     * a converter handing back its input makes every later step free to mutate
     * a caller's record in place.
     */
    const input: Record<string, unknown> = { schemaVersion: 1, id: 'c-1' };
    const { record, applied } = applyChain(input, 1, 2, CAMPAIGN_MIGRATIONS);
    expect(record).not.toBe(input);
    expect(record).toEqual(input);
    expect(applied).toHaveLength(1);
  });

  it('reads a v1 record into a campaign with nothing missing and nothing invented', () => {
    const { campaign, warnings } = readCampaignRecord(readFixture(1));
    // Same exception as the walk: the frozen fixture's party row is a stub, and
    // this test is about the session list rather than the board.
    expect(warnings.filter((w) => !w.includes('not a whole character'))).toEqual([]);
    // A v1 record has neither of the two new kinds in it, and this build must
    // not conjure one - an empty `url` row appearing here would mean the reader
    // was inventing rows rather than reading them.
    expect(campaign.session.map((i) => i.kind)).not.toContain('url');
    expect(campaign.session.map((i) => i.kind)).not.toContain('note');
    expect(campaign.session).toHaveLength(5);
  });
});

describe('the v2 fixture, which is the first one with the new rows in it', () => {
  const v2 = (): Campaign => readCampaignRecord(readFixture(2)).campaign;

  it('is seven rows, the five from v1 and the two the bump is for', () => {
    expect(v2().session.map((i) => i.kind)).toEqual([
      'scene',
      'encounter',
      'countdown',
      'link',
      'link',
      'url',
      'note',
    ]);
  });

  it('keeps the web address exactly as the parser normalises it', () => {
    const row = v2().session.find((i) => i.kind === 'url');
    expect(row?.kind === 'url' && row.href).toBe(
      'https://maps.example.org/sablewood/ford?layer=winter',
    );
    expect(row?.name).toBe("The table's map board");
  });

  it('keeps the note’s centred heading, its emphasis and its bullets', () => {
    // Every one of the four things the format exists to carry, in one fixture,
    // because a fixture that only proves paragraphs survive proves the easy
    // half of a format whose hard half is centring.
    const row = v2().session.find((i) => i.kind === 'note');
    expect(row?.kind === 'note').toBe(true);
    if (row?.kind !== 'note') return;

    const heading = row.note[0]!;
    expect(heading.type).toBe('heading');
    expect(heading.type !== 'bullets' && heading.align).toBe('center');
    expect(heading.type !== 'bullets' && heading.spans[0]!.bold).toBe(true);

    const paragraph = row.note[1]!;
    expect(paragraph.type !== 'bullets' && paragraph.spans.map((s) => s.text).join('')).toBe(
      'Rhys wants the cargo, not the fight. She will say so only if someone asks her name.',
    );
    expect(paragraph.type !== 'bullets' && paragraph.spans.some((s) => s.italic)).toBe(true);

    const bullets = row.note[2]!;
    expect(bullets.type).toBe('bullets');
    expect(bullets.type === 'bullets' && bullets.items).toHaveLength(3);
  });
});
